"""
synthetic_data.py — every password in this project comes from here.

SYNTHETIC_WORDLIST is generated by combining a small set of well-known
*generic* weak-password patterns (words like "dragon", "sunshine",
"letmein" are widely known culturally as classic weak choices — this
list is not copied from any real breach corpus) with common suffixes,
to produce a deterministic list of a few hundred fake passwords.

TARGET_SCENARIOS are the specific passwords the demo "attacks" — chosen
deliberately to illustrate different outcomes (see README for the full
walkthrough of why each one was picked).
"""

_BASE_WORDS = [
    "password", "dragon", "sunshine", "letmein", "monkey", "master",
    "welcome", "shadow", "qwerty", "football", "baseball", "superman",
    "princess", "starwars", "freedom", "whatever", "trustno1", "admin",
    "login", "iloveyou", "hunter", "ninja", "cookie", "penguin",
]
_SUFFIXES = ["", "1", "12", "123", "007", "99", "21", "2020", "2021", "2022", "2023", "2024"]


def _generate_wordlist() -> list[str]:
    words = []
    for base in _BASE_WORDS:
        for suffix in _SUFFIXES:
            words.append(base + suffix)
            words.append(base.capitalize() + suffix)
    # de-duplicate while preserving order
    seen = set()
    out = []
    for w in words:
        if w not in seen:
            seen.add(w)
            out.append(w)
    return out


SYNTHETIC_WORDLIST: list[str] = _generate_wordlist()

